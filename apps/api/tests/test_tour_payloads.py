"""Drift check for the onboarding tour's code panes (apps/web/src/features/tour/payloads/*.txt).

The payloads are generated by scripts/tour_payloads.py from the real code on a freshly seeded canonical DB. If the
agents code, the prompt, the cassettes or the two web files they quote change, this fails until someone runs
`make tour-payloads` and commits the result, so a pane never shows code or output the repo no longer has.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

API_DIR = Path(__file__).resolve().parents[1]
SCRIPT = API_DIR / "scripts" / "tour_payloads.py"
COMMITTED = API_DIR.parents[1] / "apps" / "web" / "src" / "features" / "tour" / "payloads"


def test_committed_tour_payloads_match_the_code(tmp_path: Path) -> None:
    # A subprocess, so nothing this test session imported or patched can leak into the generator.
    subprocess.run([sys.executable, str(SCRIPT), "--out", str(tmp_path)], cwd=API_DIR, check=True, capture_output=True)
    fresh = {p.name: p.read_bytes() for p in sorted(tmp_path.glob("*.txt"))}
    committed = {p.name: p.read_bytes() for p in sorted(COMMITTED.glob("*.txt"))}
    assert sorted(fresh) == sorted(committed), "payload file set changed; run `make tour-payloads`"
    stale = [name for name in fresh if fresh[name] != committed[name]]
    assert not stale, f"stale tour payloads {stale}; run `make tour-payloads` and commit the result"
