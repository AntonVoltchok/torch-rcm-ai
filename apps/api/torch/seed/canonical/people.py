def add_named_patients(b: Builder, verified_at: datetime) -> dict[str, tuple[Patient, object]]:
    """Create the named patients and primary coverages. Returns key → (patient, coverage)."""
    out: dict[str, tuple[Patient, object]] = {}
    for n in NAMED:
        p = b.patient(f"pat_{n.key}", n.first, n.last, n.dob, n.location)
        cov = b.coverage(
            p,
            n.payer,
            schedule=n.schedule,
            subscriber_id=n.subscriber_id,
            group_no=n.group_no,
            plan_name=n.plan_name,
            self_funded=n.self_funded,
            verified_at=verified_at,
            plan=dict(n.plan),
        )
        out[n.key] = (p, cov)
    # Secondary coverages: Abara (Cigna behind MetLife), Akers (Guardian behind Delta).
    abara, _ = out["abara_w"]
    b.coverage(
        abara,
        PayerKey.CIGNA,
        schedule="cigna_dppo",
        subscriber_id="U49213307",
        group_no="3337851",
        plan_name="Cigna DPPO (spouse)",
        order=CoverageOrder.SECONDARY,
        verified_at=verified_at,
    )
    akers, _ = out["akers_d"]
    b.coverage(
        akers,
        PayerKey.GUARDIAN,
        schedule="guardian_ppo",
        subscriber_id="552082790",
        group_no="00744",
        plan_name="Guardian DentalGuard Preferred (spouse)",
        order=CoverageOrder.SECONDARY,
        self_funded=True,
        verified_at=verified_at,
    )
    return out


def default_verified(now: datetime) -> datetime:
    return dt(now.date(), "06:12")
